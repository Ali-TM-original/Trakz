const getRandomLevel = (difficulty) => {

    let levelKeys;
    let alllevels;
    if (difficulty === "easy") {
        levelKeys = Object.keys(easylevels);
        alllevels = easylevels;
    } else {
        levelKeys = Object.keys(hardlevels);
        alllevels = hardlevels;
    }
    // Math.floor(Math.random() * levelKeys.length)
    const randomKey = levelKeys[Math.floor(0 * levelKeys.length)];
    const levelArray = alllevels[randomKey];
    return levelArray;
}

